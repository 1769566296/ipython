# 算数运算和平常的数学规则一致
m = 4 + 2
print(f"4+2= {m}""是", type(m), "类型")
m = 4 - 2
print(f"4-2= {m}""是", type(m), "类型")
m = 4 * 2
print(f"4*2= {m}""是", type(m), "类型")
m = 4 ** 2
print(f"4**2= {m}""是", type(m), "类型")
m = 4 / 2
print(f"4/ 2= {m}""是", type(m), "类型")
m = 4 // 2
print(f"4//2= {m}""是", type(m), "类型")
m = 4 % 2
print(f"4%2= {m}""是", type(m), "类型")
